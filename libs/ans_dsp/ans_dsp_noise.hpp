#ifndef ANS_DSP_NOISE_HPP
#define ANS_DSP_NOISE_HPP

#include <cassert>
#include <cstdint>

namespace ans_dsp
{
    /**
     * Generates a pseudo-random number using the xorshift32 algorithm.
     *
     * The xorshift32 algorithm is a simple pseudorandom number generator
     * that performs bitwise XOR and bit shifts on the input state to produce
     * the next state. The input state must not be zero.
     *
     * @param state The initial state of the xorshift32 generator. Must not be zero.
     * @return The next state in the xorshift32 sequence.
     */
    inline uint32_t get_xorshift32_next_state(uint32_t state)
    {
        if (state == 0u)
        {
            assert(!"generate noise xorshift32: state must not be zero");
            return 1u;
        }

        state ^= state << 13;
        state ^= state >> 17;
        state ^= state << 5;

        return state;
    }

    /**
     * Generates a pseudo-random noise value scaled by a given factor.
     *
     * This method uses a pseudo-random state value to generate a noise output
     * within a bipolar range (e.g., -1.0 to 1.0) which is then scaled by the
     * specified scalar factor. The `uint32_to_bipolar` function is used to map
     * the 32-bit input state to the bipolar range.
     *
     * @param state A 32-bit pseudo-random input state. Should be generated by a
     *              deterministic method such as `get_xorshift32_next_state`.
     * @param scalar A scaling factor applied to the generated bipolar noise value.
     *               Defaults to 1.0 if not provided.
     * @return A scaled bipolar noise value derived from the input state.
     */
    inline double generate_noise(const uint32_t state, const double scalar = 1.0)
    {
        return uint32_to_bipolar(state) * scalar;
    }
}
#endif
